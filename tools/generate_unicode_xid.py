"""Regenerate the checked-in Unicode 17.0.0 identifier ranges (offline).

Download https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt,
then pass its path to this script. Normal builds do not need the source data,
Python, a network connection or a system Unicode library for identifiers.
"""
import argparse
import hashlib
from pathlib import Path

VERSION = '17.0.0'
# Filled from the versioned Unicode Character Database, never the host runtime.
SHA256 = '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('data', type=Path)
    parser.add_argument('--output', type=Path,
                        default=Path(__file__).resolve().parents[1] /
                        'src/front/unicode_xid.inc')
    args = parser.parse_args()
    data = args.data.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        parser.error(f'expected unmodified Unicode {VERSION} DerivedCoreProperties.txt')
    ranges = {'XID_Start': [], 'XID_Continue': []}
    for line in data.decode('utf-8').splitlines():
        fields = line.split('#', 1)[0].strip().split(';')
        if len(fields) != 2 or fields[1].strip() not in ranges:
            continue
        bounds = fields[0].strip().split('..')
        first, last = int(bounds[0], 16), int(bounds[-1], 16)
        dest = ranges[fields[1].strip()]
        if dest and first == dest[-1][1] + 1:
            dest[-1] = (dest[-1][0], last)
        else:
            assert not dest or dest[-1][1] < first
            dest.append((first, last))
    lines = [
        '// clang-format off',
        '// Generated by tools/generate_unicode_xid.py; do not edit.',
        f'// Unicode {VERSION}: https://www.unicode.org/Public/{VERSION}/ucd/DerivedCoreProperties.txt',
        f'// Source SHA-256: {SHA256}',
        '// Unicode data license: 3rdparty/unicode/LICENSE.txt',
        '',
    ]
    for prop, entries in ranges.items():
        lines.append(f'constexpr Range k{prop.replace("_", "")}[] = {{')
        lines.extend(f'    {{0x{first:04x}, 0x{last:04x}}},' for first, last in entries)
        lines += ['};', '']
    lines += ['// clang-format on', '']
    args.output.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
